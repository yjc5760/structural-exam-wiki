def confirm_problem(qid):
    p = "raw/solutions/%s/%s-problem.md" % (qid, qid)
    t = open(p, encoding="utf-8").read()
    if "**已確認**" in t:
        return "skip"
    o1 = "> 判讀清單經使用者確認前，狀態為「待確認」；確認後本檔原則上不再修改（改動須回考卷原圖並記 log）。"
    o2 = "| 判讀狀態 | **待確認**（轉錄"
    assert o1 in t and o2 in t, qid
    t = t.replace(o1, "> 判讀清單已確認（凍結）；本檔原則上不再修改（改動須回考卷原圖並記 log）。")
    t = t.replace(o2, "| 判讀狀態 | **已確認**（%s 關卡一：使用者授權依建議判讀確認；轉錄" % D)
    t = t.replace("請確認：", "使用者授權依建議定案：")
    assert "請確認" not in t and "待確認" not in t, qid
    t = t.rstrip("\n") + "\n\n*確認：%s 使用者授權依建議判讀確認（SM-U1-3 題目正本推廣・批 2，關卡一；使用者指示「要確認的依你建議」）*\n" % D
    open(p, "w", encoding="utf-8").write(t)
    return "done"

def build(qid, s):
    L = [HDR, "", LEAD.format(id=qid), ""]
    if s["fig"]:
        L += ["![%s](figs/%s-fig-1-problem.svg)" % (s["fig"][0], qid), "", "*%s*" % s["fig"][1], ""]
    L += ["### 常見誤讀", "", "| 項目 | 正確判讀 | 常見誤讀 |", "|---|---|---|"]
    L += ["| %s | %s | %s |" % r for r in s["rows"]]
    L += ["", s["note"], ""]
    return "\n".join(L) + "\n"

