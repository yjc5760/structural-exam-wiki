def swap_svg(s, cap_key, svg):
    i = s.index(cap_key)
    a = s.rfind("<svg", 0, i)
    b = s.index("</svg>", a) + len("</svg>")
    assert b < i
    return s[:a] + svg + s[b:]


def block(s, start_key, end_key, new):
    a = s.index(start_key)
    b = s.index(end_key, a)
    return s[:a] + new + s[b:]


def rep(s, old, new):
    assert s.count(old) == 1, old[:70]
    return s.replace(old, new)


