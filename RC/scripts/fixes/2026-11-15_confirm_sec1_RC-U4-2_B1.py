    lines = t.split("\n")
    s = next(i for i, l in enumerate(lines) if l.startswith("## 1"))
    e = next(i for i, l in enumerate(lines) if l.startswith("## 2"))
    old = "\n".join(lines[s:e])
    for png in re.findall(r"\]\(([^)]+\.png)\)", old):
        if not (d / png).exists():
            print(q, "舊 §1 引用的", png, "不存在（死連結，隨 §1 改寫移除）"); continue
        assert Path(png).name in pm, (q, png)
    keep = [m.group(1).rstrip() for m in re.finditer(r"(!\[[^\]]*\]\((figs/[^)]+\.svg)\)(?:\n\n?\*[^\n]*\*)?)", old + "\n")]
    new = ["## 1. 題目（考卷原文見題目正本）", "", LEAD.format(q=q), ""]
    if v["fig"]:
        alt, cap = v["fig"]
        svg = f"figs/{q}-fig-1-problem.svg"
        assert (d / svg).exists(), (q, svg)
        new += [f"![{alt}]({svg})", f"*{cap}*", ""]
    if v["warn"]:
        new += [f"> ⚠️ **待勘誤：** {v['warn']}", ""]
    new += ["### 常見誤讀", "", T(v["rows"]), "", f"**本解記號：** {v['sym']}", ""]
    if keep:
        new += ["#### 判讀圖解（解析自繪）", ""] + sum([[k, ""] for k in keep], [])
    new += ["---", ""]
    lines[s:e] = new
    t = "\n".join(lines).rstrip("\n")
    extra = "，插入重繪附圖 figs/" + f"{q}-fig-1-problem.svg" if v["fig"] else ""
    t += f"\n\n*修正日期：{D}（§1 改為指向題目正本{extra}；舊 §1 重述改寫為常見誤讀與本解記號；本行非答案勘誤）*\n"
    assert t.count("## 1. 題目（考卷原文見題目正本）") == 1
    assert "$" not in t.rsplit("*修正日期", 1)[1]
    for k in keep:
        assert k in t
    p.write_text(t, encoding="utf-8")
    print(q, "§1 已改寫；保留自繪圖", len(keep))
