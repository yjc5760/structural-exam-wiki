def fig13_1():
    W, H = 900, 520
    o = T(450, 26, '下冊種子樹：5 顆種子 → 10 條要能寫出來的式子（右側為章號）', 16, INK, 'middle', 'bold')
    ys = [90 + i * 92 for i in range(5)]
    pos = {}
    for (k, t, col), y in zip(SEEDS, ys):
        o += R(30, y - 28, 190, 56, '#fffde7', '#fbc02d', 2, 10)
        o += T(56, y + 6, k, 16, col, 'start', 'bold')
        o += T(96, y + 6, t, 15, INK, 'start', 'bold')
        pos[k] = (220, y, col)
    fy = [70 + i * 44 for i in range(len(FORMS))]
    for (t, src, ch), y in zip(FORMS, fy):
        for s in src:
            x1, y1, col = pos[s]
            o += L(x1, y1, 390, y, col, 1.4, op=0.7)
    for (t, src, ch), y in zip(FORMS, fy):
        o += R(390, y - 17, 450, 34, '#fff', MUT, 1, 6)
        o += T(400, y + 5, t, 14, INK, 'start')
        o += T(868, y + 5, ch, 15, KEY, 'middle', 'bold')
    return svg(W, H, o, '下冊種子樹')


