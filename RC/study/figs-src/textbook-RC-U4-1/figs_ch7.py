def fig7_1():
    W, H = 900, 560
    o = T(450, 26, '上冊種子樹：4 顆種子 → 11 條要能寫出來的式子（右側為章號）', 16, INK, 'middle', 'bold')
    ys = [110 + i * 110 for i in range(4)]
    pos = {}
    for (k, t, col), y in zip(SEEDS, ys):
        o += R(30, y - 30, 190, 60, '#fffde7', '#fbc02d', 2, 10)
        o += T(56, y + 6, k, 16, col, 'start', 'bold')
        o += T(96, y + 6, t, 15, INK, 'start', 'bold')
        pos[k] = (220, y, col)
    fy = [70 + i * 44 for i in range(len(FORMS))]
    for (t, src, ch), y in zip(FORMS, fy):
        for s in src:
            x1, y1, col = pos[s]
            o += L(x1, y1, 400, y, col, 1.4, op=0.7)
    for (t, src, ch), y in zip(FORMS, fy):
        o += R(400, y - 17, 430, 34, '#fff', MUT, 1, 6)
        o += T(412, y + 5, t, 14, INK, 'start')
        o += T(862, y + 5, ch, 15, KEY, 'middle', 'bold')
    return svg(W, H, o, '上冊種子樹')


