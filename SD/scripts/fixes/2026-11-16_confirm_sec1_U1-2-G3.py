FOOT = "*修正日期：2026-11-16（§1 改為指向題目正本，重繪附圖 figs/{id}-fig-1-problem.svg）*\n"

def run(pid):
    path = os.path.join(BASE, pid, f"{pid}.md")
    raw = open(path, encoding="utf-8", newline="").read()
    crlf = "\r\n" in raw                                        # 保留原檔換行格式
    s = raw.replace("\r\n", "\n")
    if MARK in s.split("\n## 2", 1)[0]:
        print(pid, "已處理，略過"); return
    m = re.search(r"^#{2} 1\..*?(?=^## 2)", s, flags=re.S | re.M)
    assert m, pid
    old = m.group(0)
    prob = open(os.path.join(BASE, pid, f"{pid}-problem.md"), encoding="utf-8").read()
    assert "**已確認**" in prob, pid
    for png in re.findall(r"\(([^)\s]+\.png)\)", old):
        assert png in prob, (pid, png)                          # 舊 §1 引用的 png 都在題目正本
        assert os.path.exists(os.path.join(BASE, pid, png)), (pid, png)
    assert not re.search(r"figs/[^)]*\.svg", old), pid           # 舊 §1 無解析自繪向量圖（無須搬移）
    d = NEW[pid]
    assert os.path.exists(os.path.join(BASE, pid, "figs", f"{pid}-fig-1-problem.svg")), pid
    new = HDR.format(id=pid) + d["fig"] + "### 常見誤讀\n\n" + d["table"] + "\n" + d["notation"] + "\n\n---\n\n"
    s = s.replace(old, new, 1)
    s = s.rstrip("\n") + "\n\n" + FOOT.format(id=pid)
    if crlf: s = s.replace("\n", "\r\n")
    open(path, "w", encoding="utf-8", newline="").write(s)
    print(pid, "§1 已改寫")

if __name__ == "__main__":
    for pid in (sys.argv[1:] or NEW): run(pid)
