def main():
    for qid, new in SEC1.items():
        p = os.path.join(BASE, qid, f"{qid}.md")
        prob = os.path.join(BASE, qid, f"{qid}-problem.md")
        assert os.path.exists(prob), prob
        raw = open(p, encoding="utf-8", newline="").read()
        nl = "\r\n" if "\r\n" in raw else "\n"      # 保留原檔換行格式
        s = raw.replace("\r\n", "\n")
        if MARK in s:
            print(qid, "已處理，略過"); continue
        m = re.search(r"^## 1\.[^\n]*\n.*?(?=^---\s*\n+^## 2[\.\s])", s, re.S | re.M)
        assert m, qid
        old = m.group(0)
        assert not re.search(r"\.(png|svg)\)", old), f"{qid} 舊 §1 有圖片引用，須先處理"
        assert s.count("\n## 1.") == 1, qid
        s2 = s[:m.start()] + new.replace("{id}", qid) + "\n" + s[m.end():]
        s2 = s2.rstrip("\n") + "\n\n" + FOOT + "\n"
        assert s2.count(MARK) == 1 and FOOT in s2
        # §2 以後內容不變
        assert s[m.end():].rstrip("\n") in s2
        open(p, "w", encoding="utf-8", newline="").write(s2.replace("\n", nl))
        print(qid, "§1 已改寫")
if __name__ == "__main__":
    main()
