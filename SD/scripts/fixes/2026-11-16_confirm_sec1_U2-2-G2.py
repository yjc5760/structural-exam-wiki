SEC1_PAT = [r"^## 1\. 原始題目重述.*?(?=^---\s*\n\s*## 2\.|^## 2\.)"]
def check_problem(qid):
    t = (SD/f"raw/solutions/{qid}/{qid}-problem.md").read_text(encoding="utf-8")
    assert "判讀狀態 | **已確認**（2026-11-16，使用者授權依 Claude 建議）" in t, qid
    assert "*確認：2026-11-16" in t, qid
def rewrite_sec1(qid):
    p = SD/f"raw/solutions/{qid}/{qid}.md"; t = p.read_text(encoding="utf-8")
    if "## 1. 題目（考卷原文見題目正本）" in t: return False
    m = None
    for pat in SEC1_PAT:
        m = re.search(pat, t, re.S | re.M)
        if m: break
    assert m, qid
    old = m.group(0)
    assert not re.findall(r"\(([^)]*?\.png)\)", old), qid          # 本組舊 §1 無證據圖
    assert not re.findall(r"\((figs/[^)]*?\.svg)\)", old), qid      # 本組舊 §1 無自繪圖
    rows, note = SEC1[qid]
    s = ["## 1. 題目（考卷原文見題目正本）", "",
         f"> 考卷原文、公式／附表、附圖與判讀清單（已確認）見 [`{qid}-problem.md`]({qid}-problem.md)。本節只列解題時最容易讀錯的地方與本解使用的記號；題意以題目正本為準。", "",
         "### 常見誤讀", "", "| 項目 | 正確判讀 | 常見誤讀 |", "|------|---------|---------|", rows, "", f"**本解記號：** {note}", ""]
    new = "\n".join(s) + "\n"
    t2 = t.replace(old, new, 1)
    assert t2 != t and t2.count("## 1. 題目（考卷原文見題目正本）") == 1
    # 只動 §1：§1 之前與 §2 之後逐字不變
    i = t.index(old); assert t2[:i] == t[:i] and t2[i+len(new):] == t[i+len(old):]
    extra = "；舊 §1 補充的符號定義移至本解記號" if qid == "SD-2007-1" else ""
    t2 = t2.rstrip("\n") + f"\n\n*修正日期：{D}（§1 改為指向題目正本{extra}）*\n"
    p.write_text(t2, encoding="utf-8"); return True
