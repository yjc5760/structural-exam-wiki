SEC1_PAT = r"^## 1\. 原始題目重述.*?(?=^---\s*\n\s*## 2\.|^## 2\.)"
def rewrite_sec1(qid):
    p = SD/f"raw/solutions/{qid}/{qid}.md"; t = p.read_text(encoding="utf-8")
    if "## 1. 題目（考卷原文見題目正本）" in t: return False
